#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build the single-file plugin from the modules in src/ibr.

The output embeds every module's source as plain text plus the data files (fingerprint
DB, syscall tables), and installs an importer for the `ibr` package when it runs.
Tracebacks keep the module's own path and line numbers, e.g.
    File ".../plugins/ida_better_reverse.py/ibr/core/binfmt.py", line 42

usage: python tools/bundle.py [out.py]          (default: ida_better_reverse.py)
"""
import base64
import gzip
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PKG = os.path.join(ROOT, "src", "ibr")
DATA = ("fingerprint.bin", "syscalls.json")

HEADER = '''#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
IDA Better Reverse — know your binary before you read a single line.

A single-file IDA Pro plugin (and standalone CLI) that enriches a disassembly with
the context you normally have to dig for by hand:

  1. Runtime/compiler detection — identifies the C runtime or compiler of a target,
     even when it is stripped and statically linked, using function byte-fingerprint
     matching (glibc 2.19-2.44, musl 1.1.24-1.2.6) across x86_64 / i386 / aarch64,
     GLIBC_2.x version requirements, the .comment toolchain string, Go/Rust build
     strings, PE Rich headers, and UPX / PyInstaller / .NET packers.
  2. FLIRT auto-apply — applies the matching glibc/musl FLIRT signature so library
     functions get their real names back.
  3. libc annotations — adds a one-line "what it does" note to recognised libc
     functions (fopen -> open a file, returns FILE*, ...).
  4. Decompiler annotations — in the pseudocode, annotates library calls and MMX/SSE
     intrinsics with their real arguments AND decoded constants. These render live via
     a Hex-Rays hook (always fresh, nothing written), or can be persisted into the
     database as reversible comments.

  - In IDA:   drop this file into the `plugins/` directory and press Ctrl-Alt-G.
  - As a CLI: `python ida_better_reverse.py <binary>`.

Your existing names and comments are never clobbered, and every change made in a run
can be reverted with one click (Undo).

This file is generated by tools/bundle.py from the modules in src/ibr (core, ports,
app, adapters); edit those, not this file.

Repo:    https://github.com/FPSZ/ida-better-reverse
License: MIT
"""
__version__ = "@@VERSION@@"

# ======================================================================
#  Bootstrap: serve the embedded `ibr` package to `import`
# ======================================================================
import importlib.abc as _abc
import importlib.util as _util
import linecache as _linecache
import os as _os
import sys as _sys


class _BundleImporter(_abc.MetaPathFinder, _abc.Loader):
    _ibr_bundle = True

    def __init__(self, sources, base):
        self.sources, self.base = sources, base

    def _path(self, name):
        return _os.path.join(self.base, *self.sources[name][0].split("/"))

    def find_spec(self, name, path=None, target=None):
        if name not in self.sources:
            return None
        return _util.spec_from_loader(name, self, origin=self._path(name),
                                      is_package=self.sources[name][0].endswith("/__init__.py"))

    def create_module(self, spec):
        return None

    def get_source(self, name):
        return self.sources[name][1] if name in self.sources else None

    def exec_module(self, module):
        path, src = self._path(module.__name__), self.sources[module.__name__][1]
        module.__file__ = path
        # tracebacks read the lines from here (mtime None: never checked against a file)
        _linecache.cache[path] = (len(src), None, src.splitlines(True), path)
        exec(compile(src, path, "exec"), module.__dict__)


def _install(sources, data):
    # a reload of this file replaces the previous copy of the package
    for f in [f for f in _sys.meta_path if getattr(f, "_ibr_bundle", False)]:
        _sys.meta_path.remove(f)
    for m in [m for m in _sys.modules if m == "ibr" or m.startswith("ibr.")]:
        del _sys.modules[m]
    try:
        base = _os.path.abspath(__file__)
    except NameError:
        base = "ida_better_reverse.py"
    _sys.meta_path.insert(0, _BundleImporter(sources, base))
    from ibr.core import resources
    resources.BUNDLED.update(data)


'''

FOOTER = '''
_install(_SOURCES, _DATA)

# ======================================================================
#  Public names (kept from the single-file versions before 2.3)
# ======================================================================
from ibr.core.detect import detect                       # noqa: E402
from ibr.core.names import canon, resolve_variant        # noqa: E402
from ibr.core.i18n import set_lang                      # noqa: E402

try:
    import idaapi                                         # noqa: F401
    _IN_IDA = True
except Exception:
    _IN_IDA = False

if _IN_IDA:
    from ibr.adapters.ida.service import *               # noqa: E402,F401,F403
    from ibr.adapters.ida.panel import open_panel        # noqa: E402,F401
    from ibr.adapters.ida.plugin import IBIPlugin, PLUGIN_ENTRY   # noqa: E402,F401


def __getattr__(name):
    """State that now lives in the package, readable under its single-file name."""
    if name == "LANG":
        from ibr.core import i18n
        return i18n.LANG
    if name == "_panel" and _IN_IDA:
        from ibr.adapters.ida import panel
        return panel._panel
    raise AttributeError(name)

if __name__ == "__main__":
    from ibr.adapters.cli import main
    main()
'''


def literal(src):
    """A raw triple-quoted literal for src, or None when src cannot be written as one."""
    if "'''" in src or src.endswith("\\") or "\r" in src:
        return None
    return "r'''" + src + "'''"


def modules():
    out = []
    for dirpath, dirs, files in os.walk(PKG):
        dirs[:] = sorted(d for d in dirs if d not in ("__pycache__", "data"))
        for fn in sorted(files):
            if not fn.endswith(".py"):
                continue
            rel = os.path.relpath(os.path.join(dirpath, fn), os.path.dirname(PKG)).replace(os.sep, "/")
            name = rel[:-3].replace("/", ".")
            if name.endswith(".__init__"):
                name = name[:-9]
            out.append((name, rel))
    return out


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "ida_better_reverse.py")
    version = re.search(r'__version__ = "([^"]+)"', open(os.path.join(PKG, "__init__.py"), encoding="utf-8").read()).group(1)
    parts = [HEADER.replace("@@VERSION@@", version), "_SOURCES = {\n"]
    for name, rel in modules():
        src = open(os.path.join(os.path.dirname(PKG), rel), encoding="utf-8").read()
        lit = literal(src)
        if lit is None:
            sys.exit("%s cannot be embedded as a raw string (contains ''' or ends with a backslash)" % rel)
        parts.append("%r: (%r, %s),\n" % (name, rel, lit))
    parts.append("}\n\n_DATA = {\n")
    sizes = []
    for fn in DATA:
        raw = open(os.path.join(PKG, "data", fn), "rb").read()
        b64 = base64.b64encode(gzip.compress(raw, 9, mtime=0)).decode("ascii")
        parts.append("%r: %r,\n" % (fn, b64))
        sizes.append("%s %d -> %d" % (fn, len(raw), len(b64)))
    parts.append("}\n")
    parts.append(FOOTER)
    text = "".join(parts)
    compile(text, out, "exec")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("modules : %d" % len(modules()))
    print("data    : %s" % "; ".join(sizes))
    print("wrote   : %s (%d bytes, v%s)" % (out, len(text.encode("utf-8")), version))


if __name__ == "__main__":
    main()
