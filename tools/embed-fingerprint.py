#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Embed the fingerprint DB (and syscall tables) into the single-file plugin.

Reads  tools/ida_better_information.src.py   (template with @@..@@ tokens)
       tools/fingerprint.bin                  (compact byte-anchor DB, from build-fingerprint.py)
       tools/syscalls.json                    (num->name per arch; optional, regenerated by gen-syscalls.py)
writes ida_better_information.py              (self-contained, ready to ship)

usage: python tools/embed-fingerprint.py [src] [fingerprint.bin] [out.py]
"""
import gzip, base64, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "ida_better_information.src.py")
fpb = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "fingerprint.bin")
out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(ROOT, "ida_better_information.py")
sysj = os.path.join(HERE, "syscalls.json")

FP_TOKEN = "@@FINGERPRINT_B64@@"
SYS_TOKEN = "@@SYSCALLS_B64@@"


def blob64(raw):
    return base64.b64encode(gzip.compress(raw, 9)).decode("ascii")


tmpl = open(src, "r", encoding="utf-8").read()
if FP_TOKEN not in tmpl:
    sys.exit("token %s not found in %s" % (FP_TOKEN, src))

fp_raw = open(fpb, "rb").read()
fp_b64 = blob64(fp_raw)
final = tmpl.replace(FP_TOKEN, fp_b64)

if os.path.exists(sysj):
    sys_raw = open(sysj, "rb").read()
    sys_b64 = blob64(sys_raw)
else:
    sys_b64 = ""
    print("warning: %s missing; syscall annotation will be disabled" % sysj)
final = final.replace(SYS_TOKEN, sys_b64)

open(out, "w", encoding="utf-8", newline="\n").write(final)

print("fingerprint : %d bytes raw -> %d b64" % (len(fp_raw), len(fp_b64)))
if sys_b64:
    print("syscalls    : %d bytes raw -> %d b64" % (len(sys_raw), len(sys_b64)))
print("wrote       : %s (%d bytes)" % (out, len(final)))
